import design as D

names = {"D0": "PB12", "D1": "PC11", "D2": "PC10", "D3": "PC9", "D4": "PC8", "D5": "PD2", "D6": "PC12", "D7": "PG10", "D8": "PG11",
         "D9": "PB4", "D10": "PB5", "D11": "PB8", "D12": "PB9", "D13": "PB6", "D14": "PB7", "D15": "PC0", "D16": "PA3", "D17": "PB1",
         "D18": "PA7", "D19": "PA6", "D20": "PC1", "D21": "PC4", "D22": "PA5", "D23": "PA4", "D24": "PA1", "D25": "PA0", "D26": "PD11",
         "D27": "PG9", "D28": "PA2", "D29": "PB14", "D30": "PB15", "D31": "PC2", "D32": "PC3"}
fn = {"D1": "SDMMC1_D3", "D2": "SDMMC1_D2", "D3": "SDMMC1_D1", "D4": "SDMMC1_D0", "D5": "SDMMC1_CMD", "D6": "SDMMC1_CK",
      "D7": "GPIO (OLED D/C)", "D8": "SPI1_SCK", "D9": "GPIO (SK6812 data: TIM3_CH1 on PB4, CHECK the alternate function)", "D10": "SPI1_MOSI",
      "D11": "I2C1_SCL", "D12": "I2C1_SDA", "D13": "USART1_TX", "D14": "USART1_RX", "D15": "ADC (A0)", "D16": "GPIO (output only on the Seed2: clock out)",
      "D17": "ADC (A2)", "D18": "ADC (A3)", "D19": "GPIO (ADC-capable)", "D20": "GPIO (ADC-capable)", "D21": "ADC (A6)", "D22": "GPIO (a DAC pin, unused as DAC)",
      "D23": "GPIO (a DAC pin, unused as DAC)", "D24": "SAI2_MCLK_B", "D25": "SAI2_SD_B", "D26": "SAI2_SD_A", "D27": "SAI2_FS_B", "D28": "SAI2_SCK_B",
      "D29": "USB_OTG_HS", "D30": "USB_OTG_HS", "D31": "ADC (PC2)", "D32": "GPIO (ADC-capable)"}
rows = ["# Seed2 DFM pin map (generated by SenarioHW/Kicad/scripts/gen_pinmap.py from design.py; version-beta, docs/spec-beta.md section 2.2)\n",
        "Daisy pin | STM32 | Function | Net\n--- | --- | --- | ---"]
for k in [f"D{i}" for i in range(33)]:
    rows.append(f"{k} | {names[k]} | {fn.get(k, 'GPIO')} | {D.SEED_PINS.get(k) or '(free)'}")
rows.append("\nAudio pads: AUDIO_IN_1/2 = `SEED_IN_L/R`, OUT 1 = left (+/-), OUT 2 = right (+/-), VCOM = `VCOM_SEED`.")
rows.append("\nAll 33 pins are used. D1-D6 = SDMMC1 (4-bit microSD, as the Seed3 Eurorack Dev Kit), D29 / D30 = USB HS (the panel USB-C: USB MIDI; **firmware update over it is NOT settled**: the STM32 ROM DFU listens on the "
            "Seed's own micro-USB), D22 / D23 (the Seed's DACs) are GPIO because the CV outs are on an MCP4728. D16 is output only (clock out). The OLED's CS is tied low in hardware; its RES is on `U_IO3`.")


def devs(prefix):
    return [p for p in D.PARTS if p["ref"].startswith(prefix)]


def pin_list(p):
    return ", ".join(f"{k}={v}" for k, v in p["pins"].items() if re.match(r"GP[AB]\d|LED\d+$", k) and v)


rows.append("""
## I2C devices (I2C1, 4.7K pull-ups, 400 kHz to 1 MHz)

Address | Device | Job
--- | --- | ---""")
for ref, addr in (("U_IO1", "0x20"), ("U_IO2", "0x21"), ("U_IO3", "0x22")):
    p = next(q for q in D.PARTS if q["ref"] == ref)
    rows.append(f"{addr} | MCP23017 `{ref}` | {pin_list(p)}. INTA / INTB are open drain, wired together to `I2C_INT` (D23). Inputs: enable the internal pull-ups (GPPU); all switches are plain switches to GND (the standard Bourns encoders have no LED).")
rows.append("0x60 | MCP4728 `U_DAC1` | 4-channel 12-bit DAC: **A = CV out 1, B = CV out 2** (C, D spare), VDD 3V3, internal 2.048 V reference, gain 1; the op-amp stage scales to 0 .. 5 V (`CVO_RF` / `CVO_RG` in design.py). Control rate (about 1 kHz). LDAC tied low. Write the CV first and raise a gate 1 to 2 ms later.")
for ref, addr in (("U_LED1", "0x40"), ("U_LED2", "0x41")):
    p = next(q for q in D.PARTS if q["ref"] == ref)
    rows.append(f"{addr} | PCA9685 `{ref}` | {pin_list(p)} (open drain, common-anode LEDs on +5V_LED, `LED_OE` high = off)")
rows.append("""
PCA9685: set OUTDRV = 0 (open drain), clear ALLCALL; the MCP4728 and the PCA9685 both answer the I2C general call: check the datasheets before sending a general-call reset.

## SK6812 chain (8 x SK6812-EC20 under the MX keys)

`LED_DATA` (D9) -> 74AHCT1G125 on +5V_LED (`U_LS1`) -> 33R -> key 1 DIN ... key 8 DIN. Drive it from a timer + DMA (or SPI), 800 kHz; keep the brightness low (the 5 V budget).

## Panel analog (74HC4051 `U_MUX1`, ADC on D15, select lines `MUX_A/B/C` from `U_IO3`)

Channel | Control
--- | ---
0 | PTL1 wiper (Bourns PTL20, left)
1 | PTL2 wiper (Bourns PTL20, right)
2 | Alps RS6011 slider (60 mm)
3 | VR1 (trim, left)
4 | VR2 (trim, right)
5 | VR3 (regular pot, left)
6 | VR4 (regular pot, right)
7 | free

## Notes for the firmware

- External codec PCM3060 on SAI2 in H/W mode: slave, 24-bit left-justified, single-ended, de-emphasis off. The Seed drives MCLK/SCK/FS (SAI2 block B master), SD_A = DAC data to the codec, SD_B = ADC data from it. Check against libDaisy's Daisy Patch SAI2 set-up.
- CV in (4): inverting stage, +-5 V maps to 3.3 .. 0 V (invert in firmware). Gate in (2) and clock in (1): inverting transistor stage (a high gate reads 0). Clock in is on D0 (EXTI12), gate in 1 / 2 on D19 / D32.
- CV out (2): MCP4728, 0 .. 5 V, control rate. Gate out (2) and clock out (1): 0 / 5 V buffers on D20 / D22 / D16, set from the audio callback (a small block size keeps the jitter low) or a timer.
- MIDI TX should be open drain if the HAL allows it (a mono TS cable in the TRS jack shorts the ring to the sleeve).
- OLED: SPI1 write-only, 4-wire (SCK D8, MOSI D10, D/C D7), CS tied low, RES from `U_IO3` GPB. The 0.96 in module is an SSD1315; the 1.3 in (alternative in KicadLibs) is an SH1106 (libDaisy has `oled_sh1106.h`).
""")
out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[3] / "SenarioOS" / "docs" / "pinmap.md"
out.write_text("\n".join(rows) + "\n")
print("pinmap written,", out)
